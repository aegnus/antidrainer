"""Build the single-file helper.

Embeds src/bench.html into src/helper.py and writes drainer-bench.py, the one file users download and run.

    python3 build.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PLACEHOLDER = "@@BENCH_HTML@@"
NOTICE = "# Generated by build.py from src/helper.py and src/bench.html. Edit those files, not this one.\n"


def main():
    html = (ROOT / "src" / "bench.html").read_text(encoding="utf-8")
    helper = (ROOT / "src" / "helper.py").read_text(encoding="utf-8")
    if "'''" in html:
        raise SystemExit("src/bench.html must not contain ''' (it is embedded in a Python raw string).")
    if html.rstrip().endswith("\\"):
        raise SystemExit("src/bench.html must not end with a backslash.")
    if helper.count(PLACEHOLDER) != 1:
        raise SystemExit("src/helper.py must contain the placeholder %s exactly once." % PLACEHOLDER)

    lines = helper.splitlines(keepends=True)
    # Keep the shebang and license header first, then the generated-file notice.
    head = 0
    while head < len(lines) and lines[head].startswith("#"):
        head += 1
    out = "".join(lines[:head]) + NOTICE + "".join(lines[head:])
    out = out.replace(PLACEHOLDER, html)

    target = ROOT / "drainer-bench.py"
    target.write_text(out, encoding="utf-8")
    compile(out, str(target), "exec")
    print("Wrote %s (%d KB)" % (target.name, len(out.encode("utf-8")) // 1024))


if __name__ == "__main__":
    main()
